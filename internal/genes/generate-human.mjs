// Writes human.go: the names of the human T-cell receptor and immunoglobulin genes (functional
// genes, ORFs and pseudogenes) in IMGT's spelling, from the HUGO Gene Nomenclature Committee's
// complete set (https://www.genenames.org; HGNC data are released under CC0). The HGNC symbol is
// the IMGT name without IMGT's slashes ("TRAV29DV5" is IMGT's "TRAV29/DV5", "TRBV20OR9-2" is
// "TRBV20/OR9-2"), which this script puts back. adaptive.go uses the list to tell a subgroup with
// one gene ("TRBV2") from one with several ("TRBV5-1").
//
//   curl -sSfLO https://storage.googleapis.com/public-download-files/hgnc/tsv/tsv/hgnc_complete_set.txt
//   node internal/genes/generate-human.mjs hgnc_complete_set.txt && gofmt -w internal/genes/human.go

import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const path = process.argv[2];
if (!path) {
  console.error('usage: node internal/genes/generate-human.mjs hgnc_complete_set.txt');
  process.exit(2);
}
const text = readFileSync(path);
const lines = text.toString('utf8').split('\n');
const header = lines[0].split('\t');
const col = (name) => header.indexOf(name);
const [symbolAt, typeAt, statusAt] = [col('symbol'), col('locus_type'), col('status')];
const TYPES = new Map([
  ['T cell receptor gene', false], ['T cell receptor pseudogene', true],
  ['immunoglobulin gene', false], ['immunoglobulin pseudogene', true],
]);

// IMGT's spelling of an HGNC symbol.
export function imgtName(symbol) {
  return symbol
    .replace(/^(TRAV[0-9-]+)(DV[0-9]+)$/, '$1/$2')
    .replace(/^([A-Z]+[0-9A-C]*?)(OR[0-9]+-[0-9]+)([A-Z]?)$/, (m, gene, orphon, letter) => `${gene}/${orphon}${letter.toLowerCase()}`);
}

const genes = [];
for (const line of lines.slice(1)) {
  const f = line.split('\t');
  const symbol = f[symbolAt];
  if (!symbol || f[statusAt] !== 'Approved' || !TYPES.has(f[typeAt])) continue;
  // V, D, J and C genes; the heavy chain's constant genes are named by isotype (IGHM, IGHG1…).
  if (!/^(TR[ABGD]|IG[HKL])[VDJC]/.test(symbol) && !/^IGH[MGAE]/.test(symbol)) continue;
  genes.push([imgtName(symbol), TYPES.get(f[typeAt])]);
}
genes.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
const digest = createHash('sha256').update(text).digest('hex');
const out = [
  '// Code generated by generate-human.mjs from the HGNC complete set; DO NOT EDIT.',
  `// HGNC complete set SHA-256 ${digest} (CC0, https://www.genenames.org).`,
  '',
  'package genes',
  '',
  '// humanGenes are the human T-cell receptor and immunoglobulin genes in IMGT\'s spelling; true for',
  '// a pseudogene.',
  'var humanGenes = geneSet{',
  ...genes.map(([name, pseudo]) => `\t${JSON.stringify(name)}: ${pseudo},`),
  '}',
  '',
];
writeFileSync(new URL('./human.go', import.meta.url), out.join('\n'));
console.log(`${genes.length} genes`);
