function pythonDoc(description) {
  const lines = [];
  for (const paragraph of description.split('\n')) {
    let line = '';
    for (const word of paragraph.split(/\s+/).filter(Boolean)) {
      if (line && line.length + word.length + 1 > 88) { lines.push(line); line = ''; }
      line += (line ? ' ' : '') + word;
    }
    lines.push(line);
  }
  return ['        """', ...lines.map((line) => line ? '        ' + line.replace(/\\/g, '\\\\').replace(/"""/g, '\\"\\"\\"') : ''), '        """'];
}
