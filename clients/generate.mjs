// Go owns the catalog. --check writes nothing. Python only in wave 8 slice 8; R follows separately.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const here = import.meta.dirname;
const catalog = JSON.parse(readFileSync(join(here, 'tools.json'), 'utf8'));
const version = /^var version = "([^"]+)"$/m.exec(readFileSync(join(here, '../main.go'), 'utf8'))[1];
const own = new Set(['call', 'tools', 'version', 'url', 'token', 'client', 'timeout', 'connect', 'catalog', 'refresh', 'permissions']);
const keywords = new Set('False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield self'.split(' '));
const snake = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/([A-Z])([A-Z][a-z])/g, '$1_$2').toLowerCase();
const pyName = (name) => keywords.has(snake(name)) ? `${snake(name)}_` : snake(name);
const quote = (text) => JSON.stringify(text).replace(/\\u2028|\\u2029/g, ' ');
function pythonDoc(description) {
  const lines = [];
  for (const paragraph of description.split('\n')) {
    let line = '';
    for (const word of paragraph.split(/\s+/).filter(Boolean)) {
      if (line && line.length + word.length + 1 > 88) { lines.push(line); line = ''; }
      line += (line ? ' ' : '') + word;
    }
    lines.push(line);
  }
  return ['        """', ...lines.map((line) => line ? '        ' + line.replace(/\\/g, '\\\\').replace(/"""/g, '\\"\\"\\"') : ''), '        """'];
}
const out = ['# Generated by clients/generate.mjs; do not edit.', 'from ._json import UNSET', '', `API_VERSION = ${catalog.api}`, `CATALOG_VERSION = ${catalog.catalogVersion}`, `POLICY_VERSION = ${catalog.policyVersion}`, '', 'class Tools:', '    """Actions generated from the host catalog; changes require window review."""'];
const names = new Set();
for (const tool of catalog.tools) {
  if (!/^[a-z][a-z0-9_]*$/.test(tool.name) || own.has(tool.name) || names.has(tool.name)) throw new Error(`Invalid or conflicting method: ${tool.name}`);
  names.add(tool.name);
  const required = tool.inputSchema.required ?? [];
  const properties = tool.inputSchema.properties ?? {};
  const args = [...required, ...Object.keys(properties).filter((key) => !required.includes(key))];
  if (new Set(args.map(pyName)).size !== args.length) throw new Error(`Argument collision: ${tool.name}`);
  const params = ['self']; let optional = false;
  for (const key of args) {
    if (!required.includes(key) && !optional) { params.push('*'); optional = true; }
    params.push(`${pyName(key)}${required.includes(key) ? '' : '=UNSET'}`);
  }
  const description = [tool.title + '.', tool.description, `Effects: ${tool.effects.join(', ')}. Window review: ${tool.review ? 'required' : 'not required'}.`, ...args.map((key) => `${pyName(key)} (${required.includes(key) ? 'required' : 'optional; omitted by default'}): ${String(properties[key].description ?? properties[key].type).replace(/[.]+$/, '')}.`), 'Returns a Result with exact int/Decimal values. None sends JSON null; UNSET omits an optional argument.'].join('\n\n');
  out.push('', `    def ${tool.name}(${params.join(', ')}):`, ...pythonDoc(description), `        return self.call(${quote(tool.name)}${args.length ? ', **{' + args.map((key) => `${quote(key)}: ${pyName(key)}`).join(', ') + '}' : ''})`);
}
const files = new Map([
 ['python/src/clonoloom/_tools.py', out.join('\n') + '\n'],
 ['python/src/clonoloom/_version.py', `# Generated by clients/generate.mjs; do not edit.\n__version__ = ${quote(version)}\n`],
 ['python/pyproject.toml', readFileSync(join(here, 'python/pyproject.toml'), 'utf8').replace(/^version = "[^"]+"$/m, `version = "${version}"`)],
]);
for (const [path, text] of files) {
  if (process.argv.includes('--check')) {
    let actual; try { actual = readFileSync(join(here, path), 'utf8'); } catch { /* missing */ }
    if (actual !== text) throw new Error(`${path} is stale; run node clients/generate.mjs`);
  } else writeFileSync(join(here, path), text);
}
console.log(`${process.argv.includes('--check') ? 'Checked' : 'Generated'} ${catalog.tools.length} Python methods; API ${catalog.api}, catalog ${catalog.catalogVersion}, policy ${catalog.policyVersion}.`);
